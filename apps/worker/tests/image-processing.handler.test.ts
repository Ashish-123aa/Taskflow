import fs from 'fs';
import os from 'os';
import path from 'path';
import sharp from 'sharp';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { imageProcessingHandler } from '../src/jobs/handlers/image-processing.handler';
import { NonRetryableJobError } from '../src/utils/errors';
import { env } from '../src/config/env';

const noopProgress = async () => {};

describe('imageProcessingHandler', () => {
  let tempDir: string;
  let originalUploadDir: string;

  beforeEach(async () => {
    tempDir = fs.mkdtempSync(path.join(os.tmpdir(), 'taskflow-image-test-'));
    originalUploadDir = env.UPLOAD_DIR;
    // env.UPLOAD_DIR is read live by the handler (it's a plain object
    // property, not re-validated), so it can be swapped per test.
    (env as { UPLOAD_DIR: string }).UPLOAD_DIR = tempDir;

    // A real 200x100 red PNG, generated by sharp itself rather than
    // checked in as a binary fixture.
    await sharp({
      create: { width: 200, height: 100, channels: 3, background: { r: 200, g: 30, b: 30 } },
    })
      .png()
      .toFile(path.join(tempDir, 'input.png'));
  });

  afterEach(() => {
    (env as { UPLOAD_DIR: string }).UPLOAD_DIR = originalUploadDir;
    fs.rmSync(tempDir, { recursive: true, force: true });
  });

  it('resizes an image to fit within the given bounds without enlarging', async () => {
    const result = await imageProcessingHandler.execute({
      jobId: '1',
      userId: 'u1',
      attempt: 1,
      updateProgress: noopProgress,
      payload: {
        storedFilename: 'input.png',
        originalFilename: 'photo.png',
        operations: { resize: { width: 100, height: 100 } },
      },
    });

    // fit: 'inside' means the 200x100 original scales down to fit within
    // 100x100 while preserving aspect ratio — width becomes 100, height
    // scales proportionally to 50, not stretched to a 100x100 square.
    expect(result.width).toBe(100);
    expect(result.height).toBe(50);
    expect(fs.existsSync(path.join(tempDir, 'generated', 'input-processed.png'))).toBe(true);
  });

  it('converts format when requested', async () => {
    const result = await imageProcessingHandler.execute({
      jobId: '1',
      userId: 'u1',
      attempt: 1,
      updateProgress: noopProgress,
      payload: {
        storedFilename: 'input.png',
        originalFilename: 'photo.png',
        operations: { format: 'webp' },
      },
    });

    expect(result.format).toBe('webp');
    expect(fs.existsSync(path.join(tempDir, 'generated', 'input-processed.webp'))).toBe(true);
  });

  it('does not enlarge an image smaller than the requested bounds', async () => {
    const result = await imageProcessingHandler.execute({
      jobId: '1',
      userId: 'u1',
      attempt: 1,
      updateProgress: noopProgress,
      payload: {
        storedFilename: 'input.png',
        originalFilename: 'photo.png',
        operations: { resize: { width: 5000, height: 5000 } },
      },
    });

    // withoutEnlargement: true — a 200x100 source asked to fit 5000x5000
    // stays 200x100, it doesn't get blown up.
    expect(result.width).toBe(200);
    expect(result.height).toBe(100);
  });

  it('throws a non-retryable error when the file does not exist', async () => {
    await expect(
      imageProcessingHandler.execute({
        jobId: '1',
        userId: 'u1',
        attempt: 1,
        updateProgress: noopProgress,
        payload: { storedFilename: 'missing.png', originalFilename: 'x.png', operations: {} },
      }),
    ).rejects.toThrow(NonRetryableJobError);
  });
});
